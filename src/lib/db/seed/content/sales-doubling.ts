/** Видеоурок: заглушка видео + короткий конспект. extra — блоки после конспекта (например, тест). */
function videoLesson(
  slug: string,
  title: L10n,
  durationMin: number,
  caption: string,
  summary: string,
  extra: Block[] = [],
): SeedLesson {
  return lesson(slug, title, durationMin, [
    video('v1', `${caption} (${durationMin} мин)`),
    h2('h1', 'Конспект урока'),
    md('t1', summary),
    ...extra,
  ]);
}

